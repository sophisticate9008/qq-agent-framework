import assert from 'node:assert/strict';
import { mkdir, writeFile } from 'node:fs/promises';
import { chromium, type Browser } from 'playwright';
import { navigateConsolePage } from './browser-navigation-smoke.ts';
import { createNativeCapabilityRuntimeFixture, capabilityUntil, capabilityObject } from '../test/fixtures/native-capability-runtime.ts';

const cleanups: Array<() => void | Promise<void>> = [];
let browser: Browser | undefined;
const fixture = await createNativeCapabilityRuntimeFixture({ after: cleanup => cleanups.push(cleanup) });
const output = new URL('../runtime/native-chat-ui-smoke/', import.meta.url);
try {
  await fixture.login();
  await fixture.configure(false);
  assert.equal((await fixture.apply()).state, 'verified');
  browser = await chromium.launch({ headless: true, args: ['--no-sandbox'],
    ...(process.env.CHROMIUM_EXECUTABLE ? { executablePath: process.env.CHROMIUM_EXECUTABLE } : {}) });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  const page = await context.newPage();
  const errors: string[] = [];
  const writes: string[] = [];
  page.on('pageerror', error => errors.push(error.message));
  page.on('request', request => { if (request.method() === 'POST') writes.push(new URL(request.url()).pathname); });
  await page.goto(fixture.origin);
  await page.locator('#token').fill(fixture.adminToken);
  await page.locator('#connect').click();
  await page.getByRole('button', { name: '断开连接', exact: true }).waitFor();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  await navigateConsolePage(page, 'access');
  await page.getByRole('heading', { name: '访问与设置', exact: true, level: 1 }).waitFor();
  assert.equal(await page.getByRole('button', { name: '保存新授权', exact: true }).count(), 0);
  assert.equal(await page.getByRole('button', { name: /批准工具|回答模型|允许本次工具/ }).count(), 0);
  await page.getByRole('button', { name: '编辑名单', exact: true }).click();
  const access = page.getByRole('dialog', { name: '主人与白名单', exact: true });
  await access.getByText('同一份白名单允许接收和回复；敏感操作核验实际主人。', { exact: true }).waitFor();
  await access.getByRole('button', { name: '关闭', exact: true }).click();
  await navigateConsolePage(page, 'adapters');
  const runtime = page.locator('#chat-runtime');
  await runtime.getByRole('button', { name: '启动聊天', exact: true }).click();
  const start = page.getByRole('dialog', { name: '启动与检查聊天', exact: true });
  await start.locator('#chat-runtime-start').click();
  await capabilityUntil(async () => (await fixture.status()).chatReady === true, 'Browser start must reach the actual native runtime');
  await start.getByRole('button', { name: '关闭', exact: true }).click();
  fixture.inbound(1);
  await capabilityUntil(() => fixture.calls.filter(call => call.method === 'session/prompt').length === 1, 'Real local prompt is required');
  const sessionId = fixture.streams.at(-1)!.sessionId;
  fixture.event('turn/start', { turn: 1 });
  assert.equal((await fixture.reply('本地浏览器集成的显式回复')).status, 'confirmed');
  fixture.event('turn/end', { turn: 1, reason: { kind: 'completed' } });
  await capabilityUntil(async () => {
    const journal = await fixture.api('/api/chat/executions');
    return Array.isArray(journal.items) && journal.items.some(row => capabilityObject(row).status === 'completed');
  }, 'Actual execution must settle');
  assert.equal(fixture.sends.length, 1);
  await navigateConsolePage(page, 'sessions');
  await page.getByRole('heading', { name: '会话与执行记录', exact: true, level: 1 }).waitFor();
  await page.locator('[data-session-key="private:123"]').waitFor();
  await page.locator('#execution-journal').waitFor();
  await navigateConsolePage(page, 'adapters');
  await runtime.getByRole('button', { name: '停止聊天', exact: true }).click();
  const stop = page.getByRole('dialog', { name: '停止聊天', exact: true });
  await stop.getByRole('button', { name: '停止聊天', exact: true }).click();
  await capabilityUntil(async () => (await fixture.status()).state === 'stopped', 'Browser stop must settle');
  await stop.getByRole('button', { name: '关闭', exact: true }).click();
  const sessions = await fixture.api('/api/chat/sessions');
  assert(Array.isArray(sessions.items) && sessions.items.some(row => capabilityObject(row).sessionId === sessionId));
  await runtime.getByRole('button', { name: '启动聊天', exact: true }).click();
  await start.locator('#chat-runtime-start').click();
  await capabilityUntil(async () => (await fixture.status()).chatReady === true, 'Browser restart must settle');
  await start.getByRole('button', { name: '关闭', exact: true }).click();
  assert.equal(fixture.calls.filter(call => call.method === 'session/prompt').length, 1, 'Restart does not replay the prompt');
  assert.equal(fixture.controls.creates, 1);
  const saved = await fixture.api('/api/chat/access');
  await fixture.api('/api/chat/access', { revision: saved.revision, owner: saved.owner, allow: ['group:456'], deny: [] });
  fixture.inbound(2);
  await capabilityUntil(async () => Number(capabilityObject((await fixture.status()).ingress).rejected) > 0, 'Revoked access must be enforced live');
  assert.equal(fixture.calls.filter(call => call.method === 'session/prompt').length, 1);
  assert(!writes.includes('/api/chat/authorization'));
  assert.deepEqual(errors, []);
  assert.deepEqual(fixture.errors, []);
  await mkdir(output, { recursive: true, mode: 0o700 });
  await page.screenshot({ path: new URL('native-runtime.png', output).pathname, fullPage: true });
  await writeFile(new URL('result.json', output), JSON.stringify({ passed: true, explicitReplies: 1, sessionsCreated: 1,
    browserStartStop: true, restartWithoutReplay: true, liveWhitelistRevocation: true }, null, 2), { mode: 0o600 });
  console.log('原生聊天浏览器验证通过：真实本地服务启停、显式回复、会话保留和白名单即时撤销。');
} finally {
  await browser?.close();
  for (const cleanup of cleanups.reverse()) await cleanup();
}
